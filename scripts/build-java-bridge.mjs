import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'

if (!process.env.JAVA_HOME) throw new Error('Set JAVA_HOME to an OpenJDK 17 JDK')
const release = await readFile(join(process.env.JAVA_HOME, 'release'), 'utf8')
const version = release.match(/^JAVA_VERSION="([^"]+)"/m)?.[1]
if (!version?.startsWith('17.')) throw new Error('The Java bridge requires OpenJDK 17')

const directory = await mkdtemp(join(tmpdir(), 'codedang-java-'))
const executable = name => process.env.JAVA_HOME ? join(process.env.JAVA_HOME, 'bin', name) : name
try {
  execFileSync(executable('javac'), ['--release', '17', '-d', directory, 'java/src/codedang/runner/Bridge.java'], { stdio: 'inherit' })
  const jar = join(directory, 'bridge.jar')
  execFileSync(executable('jar'), ['--create', '--file', jar, '--date=2022-01-01T00:00:00Z', '-C', directory, 'codedang'], { stdio: 'inherit' })
  const bytes = await readFile(jar)
  await writeFile(resolve('src/backends/java/bridge.generated.ts'),
    `// Generated by npm run build:java. Source: java/src/codedang/runner/Bridge.java\nexport const bridgeJar = '${bytes.toString('base64')}'\n`)
  const compilerDirectory = join(directory, 'compiler')
  execFileSync(executable('jmod'), ['extract', '--dir', compilerDirectory,
    join(process.env.JAVA_HOME, 'jmods', 'jdk.compiler.jmod')], { stdio: 'inherit' })
  await mkdir('java/assets', { recursive: true })
  execFileSync(executable('jar'), ['--create', '--file', 'java/assets/javac-17.jar',
    '--date=2022-01-01T00:00:00Z', '-C', join(compilerDirectory, 'classes'), 'com',
    '-C', join(compilerDirectory, 'classes'), 'sun'], { stdio: 'inherit' })
  const compiler = await readFile('java/assets/javac-17.jar')
  const manifest = { id: 'openjdk-javac', version, assets: [{
    path: '/javac-17.jar', url: 'javac-17.jar', size: compiler.length,
    sha256: createHash('sha256').update(compiler).digest('hex')
  }] }
  await writeFile('src/languages/java/toolchain.generated.ts',
    `// Generated by npm run build:java from OpenJDK ${version}.\nimport type { ToolchainManifest } from '../../toolchains/manifest'\n\nexport const javaCompiler: ToolchainManifest = ${JSON.stringify(manifest, null, 2)}\n`)
  for (const name of ['LICENSE', 'ASSEMBLY_EXCEPTION', 'ADDITIONAL_LICENSE_INFO']) {
    const destination = join('java/assets', name)
    await rm(destination, { force: true })
    await writeFile(destination, await readFile(join(process.env.JAVA_HOME, 'legal', 'jdk.compiler', name)))
  }
  await writeFile('java/assets/NOTICE', `javac extracted from Eclipse Temurin OpenJDK ${version}.\n` +
    `Source: https://github.com/adoptium/jdk17u (jdk.compiler module).\n` +
    `SOURCE revision: ${release.match(/^SOURCE="([^"]+)"/m)?.[1]}\n` +
    `Corresponding source: https://github.com/adoptium/jdk17u/tree/${release.match(/^SOURCE="\.:git:([^"]+)"/m)?.[1]}/src/jdk.compiler\n` +
    'Licensed under GPLv2 with the Classpath Exception. See accompanying license files.\n' +
    'Rebuild with npm run build:java using the matching OpenJDK JDK.\n')
} finally {
  await rm(directory, { recursive: true, force: true })
}
