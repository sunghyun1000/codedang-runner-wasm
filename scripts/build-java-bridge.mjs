import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { prepareJavaToolchain } from './prepare-java-toolchain.mjs'

// This builds only our bridge. Compiler binaries are downloaded separately.
if (!process.env.JAVA_HOME) throw new Error('Set JAVA_HOME to a Java 17+ JDK')
await prepareJavaToolchain()
const compiler = JSON.parse(await readFile(new URL('../src/languages/java/toolchain.json', import.meta.url), 'utf8'))
const compilerJar = new URL('../.toolchains/java/' + compiler.assets[0].url, import.meta.url)

const executable = name => join(process.env.JAVA_HOME, 'bin', name)
const directory = await mkdtemp(join(tmpdir(), 'codedang-java-'))
try {
  execFileSync(executable('javac'), ['--release', '17', '-cp', fileURLToPath(compilerJar), '-d', directory, 'src/languages/java/bridge/Bridge.java'], { stdio: 'inherit' })
  const jar = join(directory, 'bridge.jar')
  execFileSync(executable('jar'), ['--create', '--file', jar, '--date=2022-01-01T00:00:00Z', '-C', directory, 'codedang'], { stdio: 'inherit' })
  const bytes = await readFile(jar)
  await writeFile(resolve('src/backends/java/bridge.generated.ts'),
    `// Generated by npm run build:java. Source: src/languages/java/bridge/Bridge.java\nexport const bridgeJar = '${bytes.toString('base64')}'\n`)
} finally {
  await rm(directory, { recursive: true, force: true })
}
